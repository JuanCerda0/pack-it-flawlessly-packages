CREATE TABLE packages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    reference VARCHAR(80),
    description VARCHAR(1000),
    status VARCHAR(24) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE package_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(80),
    product_name VARCHAR(160) NOT NULL,
    quantity INTEGER NOT NULL,
    package_id BIGINT NOT NULL REFERENCES packages (id)
);

CREATE INDEX idx_packages_created_at ON packages (created_at DESC);
CREATE INDEX idx_packages_status_created_at ON packages (status, created_at DESC);
CREATE INDEX idx_package_items_package_id ON package_items (package_id);
